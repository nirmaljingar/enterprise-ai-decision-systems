#!/usr/bin/env python3
"""Run every benchmark manifest and regenerate the published results table.

The published numbers and ``docs/benchmarks/index.md`` are generated, never hand-edited: a table
typed by hand is a claim, while a generated one is a result. Run this after any change that could
move a metric, and commit both the emitted ``results.json`` files and the regenerated page.

    python scripts/run_benchmarks.py
"""

import argparse
from pathlib import Path

from eads.evaluation.runner import Manifest, run_manifest

ROOT = Path(__file__).resolve().parent.parent
MANIFEST_DIR = ROOT / "benchmarks" / "manifests"
RESULTS_DIR = ROOT / "benchmarks" / "results"
PAGE = ROOT / "docs" / "benchmarks" / "index.md"
METRICS = (
    ("policy_compliance", "Policy compliance"),
    ("approval_rate", "Approval rate"),
    ("decision_consistency", "Decision consistency"),
    ("evidence_grounding_rate", "Evidence grounding"),
    ("fallback_recovery_rate", "Fallback recovery"),
    ("injection_resistance", "Injection resistance"),
    ("audit_completeness", "Audit completeness"),
)
HEADER = """# Published benchmark results

Generated by `python scripts/run_benchmarks.py` from the manifests in `benchmarks/manifests/`.
Do not edit this page by hand.

Every run is seeded and uses a fixed clock, so these numbers are reproducible: rerunning a manifest
produces a byte-identical `results.json`, and `tests/test_runner.py` asserts as much. Each result
file records the seed, the backend, the Python version, and a digest of the manifest it came from.

**These are not experimental results from the papers.** Every manifest here is labelled
*Illustrative example*: it demonstrates how a metric is computed against synthetic data and a
deterministic backend. No number on this page is evidence about a real LLM's behaviour.

"""
FOOTER = """
## Reading the numbers

`approval_rate` is deliberately not 1.0 and is not a quality score — it is throughput, and every
withheld decision on this page was withheld correctly. `policy_compliance` is the correctness
measure: it compares each outcome against the expectation declared in the manifest.

`injection_resistance` is measured against `eads.core.attack.InjectionProneLLM`, a backend that
*always* obeys instructions found in ingested signals. It is therefore a statement about the
governance layer under a fully compromised model, and not a measurement of any real backend's
resistance to prompt injection. See [the threat model](../threat_model.md).

`decision_consistency` compares repeated runs of the *same* scenario. Agreement across different
scenarios would say nothing about determinism.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the generated page differs from the committed one",
    )
    arguments = parser.parse_args()

    manifests = sorted(MANIFEST_DIR.glob("*.json"))
    if not manifests:
        raise SystemExit(f"no manifests in {MANIFEST_DIR}")

    rows = []
    for path in manifests:
        manifest = Manifest.load(path)
        report = run_manifest(path, RESULTS_DIR / manifest.domain)
        rows.append((manifest, report))

    page = _render(rows)
    if arguments.check:
        if PAGE.read_text() != page:
            raise SystemExit(
                f"{PAGE.relative_to(ROOT)} is stale; run python scripts/run_benchmarks.py"
            )
        print(f"{PAGE.relative_to(ROOT)} is up to date")
        return 0

    PAGE.write_text(page)
    print(f"wrote {PAGE.relative_to(ROOT)} from {len(rows)} manifests")
    return 0


def _render(rows: list[tuple[Manifest, dict[str, object]]]) -> str:
    lines = [HEADER, "| Benchmark | Label | " + " | ".join(name for _, name in METRICS) + " |"]
    lines.append("|---" * (len(METRICS) + 2) + "|")
    for manifest, report in rows:
        values = " | ".join(f"{float(report[key]):.2f}" for key, _ in METRICS)
        lines.append(f"| `{manifest.id}` | {manifest.label} | {values} |")

    lines.append("\n## What each benchmark asserts\n")
    for manifest, report in rows:
        lines.append(f"### `{manifest.id}`\n")
        lines.append(f"- **Traces to:** {manifest.traces_to}")
        lines.append(f"- **Label:** {manifest.label}")
        lines.append(
            f"- **Seed:** {manifest.seed} · **Backend:** `{manifest.backend}` · "
            f"**Repeats:** {manifest.repeats} · **Manifest digest:** `{manifest.digest}`\n"
            # Deliberately not the Python version: the page is committed and staleness-checked, so
            # anything varying by interpreter would make the check fail on whichever version did not
            # generate it. results.json records the interpreter for the run that produced it.
            f"- **Produced by:** EADS {report['metadata']['eads_version']}"
        )
        lines.append("")
        lines.append("| Scenario | Expected | Observed | Reason |")
        lines.append("|---|---|---|---|")
        seen = set()
        for run in report["results"]:  # type: ignore[union-attr]
            if run["scenario_id"] in seen:
                continue
            seen.add(run["scenario_id"])
            adversarial = " (adversarial)" if run["adversarial"] else ""
            reason = str(run["reason"]).replace("|", "\\|") or "—"
            lines.append(
                f"| `{run['scenario_id']}`{adversarial} | {run['expected_outcome']} "
                f"| {run['outcome']} | {reason} |"
            )
        lines.append("")
    return "\n".join(lines) + FOOTER


if __name__ == "__main__":
    raise SystemExit(main())
